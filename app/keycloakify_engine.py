def keycloakify_tool_status() -> dict[str, Any]:
    commands = {name: shutil.which(name) for name in ("node", "npm", "java", "mvn")}
    versions: dict[str, str | None] = {}
    incompatible: list[str] = []
    checks = {
        "node": ["node", "--version"],
        "npm": ["npm", "--version"],
        "java": ["java", "-version"],
        "mvn": ["mvn", "-version"],
    }
    parsed: dict[str, tuple[int, int] | None] = {}
    for name, command in checks.items():
        if not commands[name]:
            versions[name] = None
            parsed[name] = None
            continue
        try:
            result = subprocess.run(command, capture_output=True, text=True, timeout=5, check=False)
            output = (result.stdout or result.stderr).strip().splitlines()
            version_text = output[0][:100] if output else "Disponible"
            versions[name] = version_text
            match = re.search(r"(?:v|version \"?)?(\d+)\.(\d+)", version_text, flags=re.IGNORECASE)
            parsed[name] = (int(match.group(1)), int(match.group(2))) if match else None
        except Exception:
            versions[name] = "Disponible"
            parsed[name] = None

    # Match the supported toolchain used by the official Keycloakify starter.
    requirements = {
        "node": lambda version: version is not None and (version[0] == 18 or version[0] >= 20),
        "npm": lambda version: version is not None and version[0] >= 8,
        "java": lambda version: version is not None and version[0] >= 17,
        "mvn": lambda version: version is not None and (version[0] > 3 or (version[0] == 3 and version[1] >= 8)),
    }
    for name, check in requirements.items():
        if commands[name] and not check(parsed[name]):
            incompatible.append(name)

    missing = [name for name, path in commands.items() if not path]
    unavailable = missing + [f"{name} (version incompatible)" for name in incompatible]
    return {
        "ready": not unavailable,
        "engine": "Keycloakify",
        "keycloakifyVersion": KEYCLOAKIFY_VERSION,
        "commands": commands,
        "versions": versions,
        "missing": unavailable,
        "incompatible": incompatible,
    }


def _css_escape_font(value: str) -> str:
    return re.sub(r"[;{}<>]", "", str(value or "system-ui"))[:160]


